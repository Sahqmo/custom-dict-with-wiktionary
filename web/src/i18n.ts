const MESSAGES: Record<Locale, Messages> = { ko, en, ja, zh, de, fr, es, eo }

/** 지금 UI 언어로 번역한 문구. 키가 없으면(있을 수 없지만) 한국어 → 키 이름 순으로 돌려준다. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const msg = MESSAGES[getSettings().locale]?.[key] ?? ko[key] ?? key
  return params ? msg.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`)) : msg
}

/** Intl API에 넘길 언어 태그 */
export const intlTag = (locale: Locale) => (locale === 'zh' ? 'zh-CN' : locale)

/** 이 환경의 Intl이 해당 UI 언어를 지원하는지 보고, 아니면 영어로 대신한다 (미지원 언어를 주면 시스템 언어로 새어 나온다). */
function supported(locale: Locale, ctor: { supportedLocalesOf(l: string[]): string[] }) {
  const tag = intlTag(locale)
  return ctor.supportedLocalesOf([tag]).length ? tag : 'en'
}

const displayNames = new Map<string, Intl.DisplayNames>()

/** 언어 코드(ko, de …)의 이름을 UI 언어로. 브라우저의 Intl이 알면 그 이름, 모르면 null. */
export function languageName(code: string, locale: Locale = getSettings().locale): string | null {
  try {
    const tag = supported(locale, Intl.DisplayNames)
    let dn = displayNames.get(tag)
    if (!dn) displayNames.set(tag, (dn = new Intl.DisplayNames([tag], { type: 'language' })))
    const name = dn.of(code)
    return name && name !== code ? name : null
  } catch {
    return null
  }
}

/** "3분 전", "어제" 같은 상대 시간을 UI 언어로 */
export function relativeTime(at: number): string {
  const locale = getSettings().locale
  const sec = Math.round((at - Date.now()) / 1000)
  const abs = Math.abs(sec)
  if (abs < 60) return t('time.now')
  const rtf = new Intl.RelativeTimeFormat(supported(locale, Intl.RelativeTimeFormat), { numeric: 'auto' })
  if (abs < 3600) return rtf.format(Math.round(sec / 60), 'minute')
  if (abs < 86400) return rtf.format(Math.round(sec / 3600), 'hour')
  if (abs < 86400 * 30) return rtf.format(Math.round(sec / 86400), 'day')
  return new Date(at).toLocaleDateString(supported(locale, Intl.DateTimeFormat))
}
